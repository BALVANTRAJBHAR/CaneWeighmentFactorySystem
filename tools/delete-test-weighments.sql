/*
  SAFE TEST WEIGHMENT CLEANUP (SQL Server)

  1. Set the last real IDs and the exact test ranges below.
  2. Keep @Execute = 0 and run once: this only previews rows/files.
  3. Verify the preview, take a backup, set @Execute = 1, then run again.

  Paid purchases are deliberately refused. Removing a payment can also change
  cash-book and loan-recovery balances, so that must be handled as a separate,
  explicitly reviewed cleanup operation.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @LastRealPurchaseId     int = 40;
DECLARE @PurchaseTestFrom       int = 41;
DECLARE @PurchaseTestTo         int = 50;

DECLARE @LastRealSaleId         int = 50;
DECLARE @SaleTestFrom           int = 51;
DECLARE @SaleTestTo             int = 60;

DECLARE @Execute bit = 0; -- 0 = PREVIEW ONLY, 1 = DELETE AFTER BACKUP

IF @PurchaseTestFrom <= @LastRealPurchaseId OR @SaleTestFrom <= @LastRealSaleId
    THROW 51000, 'Test ranges overlap the protected real-data cutoff.', 1;
IF @PurchaseTestFrom > @PurchaseTestTo OR @SaleTestFrom > @SaleTestTo
    THROW 51001, 'A test-range start cannot be greater than its end.', 1;

BEGIN TRANSACTION;

SELECT Id INTO #PurchaseIds
FROM Purchases WITH (UPDLOCK, HOLDLOCK)
WHERE Id BETWEEN @PurchaseTestFrom AND @PurchaseTestTo;

SELECT Id INTO #SaleIds
FROM SalePurchases WITH (UPDLOCK, HOLDLOCK)
WHERE Id BETWEEN @SaleTestFrom AND @SaleTestTo;

-- A paid purchase is not a standalone weighment anymore. Abort instead of
-- risking a real payment, cash-book entry or loan recovery.
IF EXISTS (SELECT 1 FROM PaymentPurchases pp JOIN #PurchaseIds x ON x.Id = pp.PurchaseId)
   OR EXISTS (SELECT 1 FROM PaymentImages pi JOIN #PurchaseIds x ON x.Id = pi.PurchaseId)
BEGIN
    ROLLBACK TRANSACTION;
    THROW 51002, 'Cleanup stopped: at least one selected purchase is linked to a payment/evidence record.', 1;
END;

SELECT 'Sugarcane Purchase' AS RecordType, p.Id, p.VehicleNumber,
       p.GrossDateTime, p.TareDateTime, p.PaymentStatus
FROM Purchases p JOIN #PurchaseIds x ON x.Id = p.Id ORDER BY p.Id;

SELECT 'Sale Weighment' AS RecordType, s.Id, s.VehicleNumber,
       s.TareDateTime, s.GrossDateTime, s.WeighmentStatus
FROM SalePurchases s JOIN #SaleIds x ON x.Id = s.Id ORDER BY s.Id;

-- Save/copy these paths if the physical image files must also be removed.
-- SQL deletes image metadata only; it intentionally cannot delete disk/blob files.
SELECT 'PurchaseImage' AS ImageType, i.PurchaseId AS RecordId, i.FilePath
FROM PurchaseImages i JOIN #PurchaseIds x ON x.Id = i.PurchaseId
UNION ALL
SELECT 'SalePurchaseImage', i.SalePurchaseId, i.FilePath
FROM SalePurchaseImages i JOIN #SaleIds x ON x.Id = i.SalePurchaseId;

IF @Execute = 0
BEGIN
    ROLLBACK TRANSACTION;
    PRINT 'PREVIEW ONLY: nothing was deleted. Verify the rows, take a backup, then set @Execute = 1.';
    RETURN;
END;

-- Rate-override audit/evidence belonging only to the selected weighments.
SELECT EvidenceId INTO #RateEvidenceIds
FROM WeighmentRateOverrides w
WHERE (w.TransactionType = 'CANE' AND EXISTS (SELECT 1 FROM #PurchaseIds x WHERE x.Id = w.TransactionId))
   OR (w.TransactionType = 'SALE' AND EXISTS (SELECT 1 FROM #SaleIds x WHERE x.Id = w.TransactionId));

DELETE w FROM WeighmentRateOverrides w
WHERE (w.TransactionType = 'CANE' AND EXISTS (SELECT 1 FROM #PurchaseIds x WHERE x.Id = w.TransactionId))
   OR (w.TransactionType = 'SALE' AND EXISTS (SELECT 1 FROM #SaleIds x WHERE x.Id = w.TransactionId));

DELETE e FROM RateOverrideEvidences e
WHERE EXISTS (SELECT 1 FROM #RateEvidenceIds x WHERE x.EvidenceId = e.Id)
   OR (e.TransactionType = 'CANE' AND EXISTS (SELECT 1 FROM #PurchaseIds x WHERE x.Id = e.TransactionId))
   OR (e.TransactionType = 'SALE' AND EXISTS (SELECT 1 FROM #SaleIds x WHERE x.Id = e.TransactionId));

DELETE i FROM PurchaseImages i JOIN #PurchaseIds x ON x.Id = i.PurchaseId;
DELETE i FROM SalePurchaseImages i JOIN #SaleIds x ON x.Id = i.SalePurchaseId;

DELETE l FROM SmsLogs l
WHERE EXISTS (SELECT 1 FROM #PurchaseIds x
              WHERE l.ReferenceId = CONCAT('PUR-', x.Id)
                 OR l.ReferenceId LIKE CONCAT('PUR-', x.Id, '-OWNER-%'))
   OR EXISTS (SELECT 1 FROM #SaleIds x
              WHERE l.ReferenceId = CONCAT('SP-', x.Id, '-PARTY')
                 OR l.ReferenceId LIKE CONCAT('SP-', x.Id, '-OWNER-%'));

DELETE a FROM AuditLogs a
WHERE (a.Entity = 'Purchase' AND TRY_CONVERT(int, a.EntityId) IN (SELECT Id FROM #PurchaseIds))
   OR (a.Entity = 'SalePurchase' AND TRY_CONVERT(int, a.EntityId) IN (SELECT Id FROM #SaleIds));

DELETE p FROM Purchases p JOIN #PurchaseIds x ON x.Id = p.Id;
DELETE s FROM SalePurchases s JOIN #SaleIds x ON x.Id = s.Id;

-- Business numbers are generated by NumberSequences, not SQL IDENTITY.
UPDATE NumberSequences
SET NextValue = ISNULL((SELECT MAX(Id) + 1 FROM Purchases), 1)
WHERE Name = 'PurchaseId';

UPDATE NumberSequences
SET NextValue = ISNULL((SELECT MAX(Id) + 1 FROM SalePurchases), 1)
WHERE Name = 'SalePurchaseId';

COMMIT TRANSACTION;
PRINT 'Selected unpaid test weighments and their direct metadata were deleted successfully.';
