[CmdletBinding()]
param(
    [string]$OutputDirectory = (Join-Path $PSScriptRoot '..\artifacts\API_DEPLOY'),

    # A fresh Azure Windows App Service needs the generated ASP.NET Core
    # Module web.config. Local IIS updates keep the existing server copy.
    [switch]$AzureAppService,

    # A brand-new local IIS site also needs the generated ASP.NET Core Module
    # web.config. Do not use this for an update over an already configured IIS
    # folder because that server may have a protected/custom web.config.
    [switch]$FreshIis,

    [string]$ZipPath
)

$ErrorActionPreference = 'Stop'

$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$apiProject = Join-Path $projectRoot 'backend\src\CaneFactory.API\CaneFactory.API.csproj'

if ($AzureAppService -and $FreshIis) {
    throw 'AzureAppService and FreshIis are mutually exclusive.'
}

if ((Test-Path -LiteralPath $OutputDirectory) -and
    (Get-ChildItem -LiteralPath $OutputDirectory -Force | Select-Object -First 1)) {
    throw "Output directory is not empty: $OutputDirectory. Use a new empty directory."
}

if ($AzureAppService) {
    # The configured cloud Web App is Windows/.NET 8. Publishing for win-x64
    # avoids shipping SkiaSharp native binaries for Linux, macOS, ARM and x86,
    # which otherwise wastes most of a Free-plan site's storage and upload time.
    dotnet publish $apiProject -c Release -r win-x64 --self-contained false -o $OutputDirectory
}
else {
    dotnet publish $apiProject -c Release -o $OutputDirectory
}
if ($LASTEXITCODE -ne 0) { throw 'API publish failed.' }

if ($AzureAppService) {
    # Cloud capture runs in EDGE_PC mode; the factory-PC edge API owns FFmpeg.
    # Excluding the 100+ MB executable makes Free-plan ZIP deployment much
    # faster and leaves more of the site's small storage quota available.
    $cloudFfmpegDirectory = Join-Path $OutputDirectory 'tools\ffmpeg'
    if (Test-Path -LiteralPath $cloudFfmpegDirectory) {
        Remove-Item -LiteralPath $cloudFfmpegDirectory -Recurse -Force
    }
    # Portable debugging symbols are useful in local development but consume
    # over 100 MB here (mostly native Skia symbols). App Service diagnostics
    # still receives structured application logs without shipping these files.
    Get-ChildItem -LiteralPath $OutputDirectory -Recurse -File -Filter '*.pdb' |
        Remove-Item -Force
}

$unsafeSettings = Join-Path $OutputDirectory 'appsettings.json'
if (Test-Path -LiteralPath $unsafeSettings) {
    throw 'Unsafe API package: source appsettings.json was included and could overwrite the server configuration.'
}

# IIS web.config often contains server-only environment variables. Keep the
# already configured server copy during an update instead of replacing it with
# the generic file generated by dotnet publish.
$generatedWebConfig = Join-Path $OutputDirectory 'web.config'
if (!$AzureAppService -and !$FreshIis -and (Test-Path -LiteralPath $generatedWebConfig)) {
    Remove-Item -LiteralPath $generatedWebConfig -Force
}

Write-Host "API deployment package created: $OutputDirectory"
if ($AzureAppService) {
    if (!(Test-Path -LiteralPath $generatedWebConfig)) {
        throw 'Azure App Service package is missing the generated web.config.'
    }
    if ([string]::IsNullOrWhiteSpace($ZipPath)) {
        $ZipPath = "$OutputDirectory.zip"
    }
    $resolvedZipParent = Split-Path -Parent $ZipPath
    if (![string]::IsNullOrWhiteSpace($resolvedZipParent)) {
        New-Item -ItemType Directory -Path $resolvedZipParent -Force | Out-Null
    }
    if (Test-Path -LiteralPath $ZipPath) {
        throw "ZIP already exists: $ZipPath. Use a new path so an existing deployment is not overwritten."
    }
    Compress-Archive -Path (Join-Path $OutputDirectory '*') -DestinationPath $ZipPath -CompressionLevel Optimal
    Write-Host "Azure App Service ZIP created: $ZipPath"
    Write-Host 'appsettings.json was excluded; generated web.config was retained for ASP.NET Core hosting.'
}
elseif ($FreshIis) {
    if (!(Test-Path -LiteralPath $generatedWebConfig)) {
        throw 'Fresh IIS package is missing the generated ASP.NET Core Module web.config.'
    }
    Write-Host 'Fresh IIS package includes generated web.config (no secrets embedded).'
    Write-Host 'Configure protected values as machine environment variables, then restart WAS/IIS.'
}
else {
    Write-Host 'appsettings.json and web.config were intentionally excluded.'
    Write-Host 'Copy this update package over the existing IIS folder without deleting its server-only configuration files.'
}
